/** `t('notify', {agent: 'Claude'})` → "Notify Claude". */
export type Translate = (key: keyof Messages, vars?: Record<string, string | number>) => string;

export function translator(messages: Messages, agent: string): Translate {
  return (key, vars = {}) => messages[key].replace(/\{(\w+)\}/g, (_, k: string) => String(k === 'agent' && !(k in vars) ? agent : vars[k] ?? ''));
}
